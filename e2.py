# Experiment 2 - Fundamental data types
# Question: Store and display robot information using int, float, complex, bool and str.
# Theme: Fundamental Python data types and type().
robot_name = "Robo"
robot_age = 2
battery_level = 85.5
sensor_value = 3 + 4j
robot_active = True

print("Robot Name:", robot_name)
print("Robot Age:", robot_age)
print("Battery Level:", battery_level)
print("Sensor Value:", sensor_value)
print("Robot Active:", robot_active)

print("\nData types:")
print("Robot Name:", type(robot_name))
print("Robot Age:", type(robot_age))
print("Battery Level:", type(battery_level))
print("Sensor Value:", type(sensor_value))
print("Robot Active:", type(robot_active))
